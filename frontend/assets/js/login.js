/*==================================================
NEXORA LOGIN
==================================================*/

document.addEventListener("DOMContentLoaded", () => {
/*==================================================
                GET LOGIN BUTTONS
==================================================*/

const googleButton = document.getElementById(
    "googleLoginButton"
);

const emailButton = document.getElementById(
    "emailLoginButton"
);

const samlButton = document.getElementById(
    "samlLoginButton"
);

const passkeyButton = document.getElementById(
    "passkeyLoginButton"
);


/*==================================================
                GOOGLE LOGIN
==================================================*/

if (googleButton) {

    googleButton.addEventListener("click", () => {

        console.log("Continue with Google clicked");

        alert(
            "Google authentication will be connected to Nexora's authentication service."
        );

    });

}


/*==================================================
                EMAIL LOGIN
==================================================*/

if (emailButton) {

    emailButton.addEventListener("click", () => {

        console.log("Continue with email clicked");

        window.location.href = "email-login.html";

    });

}


/*==================================================
                SAML SSO
==================================================*/

if (samlButton) {

    samlButton.addEventListener("click", () => {

        console.log("SAML SSO clicked");

        alert(
            "SAML SSO will be connected to enterprise authentication."
        );

    });

}


/*==================================================
                PASSKEY LOGIN
==================================================*/

if (passkeyButton) {

    passkeyButton.addEventListener("click", async () => {

        console.log("Passkey login clicked");


        /*------------------------------------------
                CHECK BROWSER SUPPORT
        ------------------------------------------*/

        if (
            !window.PublicKeyCredential ||
            !navigator.credentials
        ) {

            alert(
                "Passkey authentication is not supported by this browser."
            );

            return;

        }


        /*
         * Real WebAuthn authentication requires
         * credentials/options generated by your
         * backend.
         *
         * This button is therefore prepared here
         * for the future backend implementation.
         */

        alert(
            "Passkey authentication will be connected to Nexora's backend."
        );

    });

};
});
